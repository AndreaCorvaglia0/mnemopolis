export function drawFrame(ctx, rows, pal, ox, oy) {
  const pad = 16 - rows.length;
  rows.forEach((row, j) => {
    for (let i = 0; i < Math.min(16, row.length); i++) {
      const ch = row[i];
      if (ch === '.' || ch === ' ') continue;
      ctx.fillStyle = ch === 'o' ? INK : pal[ch] || '#ff00ff';
      ctx.fillRect(ox + i, oy + pad + j, 1, 1);
    }
  });
  // a soft shadow under ground animals is drawn by the scene; here only the light from the upper left
}

export function animalSheet(name) {
  const [frames, pal] = SHEETS[name];
  const [c, ctx] = makeCanvas(16 * frames.length, 16);
  frames.forEach((f, k) => drawFrame(ctx, F[f], PALS[pal], k * 16, 0));
  return c;
}
